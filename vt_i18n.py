def tr(lang: str, key: str, **kwargs) -> str:
    table = TR.get(lang) or TR["en"]
    text = table.get(key, TR["en"].get(key, key))
    if kwargs:
        try:
            text = text.format(**kwargs)
        except (KeyError, IndexError, ValueError):
            pass
    return text
